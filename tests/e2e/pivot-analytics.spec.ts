import {expect,test} from './account-fixture';
import * as XLSX from 'xlsx';
test('Top N, percent of grand and drill-down use full filtered totals',async({page})=>{
 const wb=XLSX.utils.book_new();XLSX.utils.book_append_sheet(wb,XLSX.utils.aoa_to_sheet([['Region','Amount'],['N',10],['N',20],['S',90]]),'Data');
 await page.goto('/');await expect(page.getByTestId('filtered-count')).toHaveText('180');
 await page.getByLabel('Chọn dữ liệu Excel',{exact:true}).setInputFiles({name:'analytics.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})});
 await expect(page.getByTestId('metric-total')).toHaveText('120');
 const panel=page.getByRole('region',{name:'Pivot nâng cao',exact:true});
 await panel.getByRole('button',{name:'Mở Pivot',exact:true}).click();
 await panel.getByLabel('Top N nhóm hàng').check();
 await panel.getByLabel('Số nhóm Top N').fill('1');
 await panel.getByLabel('Tỷ trọng chỉ số 1').selectOption('grand');
 await panel.getByRole('button',{name:'Kiểm tra Pivot',exact:true}).click();
 const matrix=panel.getByTestId('pivot-matrix'),alert=panel.getByRole('alert');
 await expect(matrix.or(alert)).toBeVisible({timeout:30000});
 if(await alert.count())throw Error(await alert.innerText());
 await expect(panel.getByTestId('pivot-ranked')).toContainText('1 nhóm ẩn');
 await expect(matrix.getByRole('rowheader',{name:'N',exact:true})).toHaveCount(0);
 const row=matrix.getByRole('row').filter({has:page.getByRole('rowheader',{name:'S',exact:true})});
 await expect(row.getByRole('cell')).toContainText('75,00');
 await row.getByRole('button').click();
 const detail=panel.getByRole('region',{name:'Chi tiết ô Pivot',exact:true});
 await expect(detail).toContainText('1 dòng nguồn');
 await expect(detail.getByRole('cell',{name:'90',exact:true})).toBeVisible();
 await detail.getByRole('button',{name:'Đóng chi tiết'}).click();
 await panel.getByRole('button',{name:'Áp dụng Pivot',exact:true}).click();
 await expect(matrix).toBeVisible();
 await expect(page.getByTestId('metric-total')).toHaveText('120');
});
