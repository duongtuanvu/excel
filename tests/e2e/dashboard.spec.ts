import {expect,test} from './account-fixture';
import * as XLSX from 'xlsx';
const excel=(name:string,rows:(string|number)[][])=>{const book=XLSX.utils.book_new();XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet(rows),'Data');return {name,mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(book,{type:'buffer',bookType:'xlsx'})};};
test('dashboard saves independent source widgets, layout and filters; replays multiple sources after reload',async({page,accountFixture})=>{
 await page.goto('/');await expect(page.getByTestId('filtered-count')).toHaveText('180');
 const upload=page.getByLabel('Chọn dữ liệu Excel',{exact:true});
 await upload.setInputFiles(excel('sales.xlsx',[['Region','Amount'],['N',10],['S',20]]));await expect(page.getByTestId('metric-total')).toHaveText('30');
 await upload.setInputFiles(excel('cost.xlsx',[['Region','Amount'],['N',3],['S',7]]));await expect(page.getByTestId('metric-total')).toHaveText('10');
 await page.getByRole('button',{name:'Dashboard Designer',exact:true}).click();
 const panel=page.getByRole('region',{name:'Dashboard Designer',exact:true}),canvas=panel.getByLabel('Bố cục Dashboard');
 await panel.getByLabel('Tên Dashboard',{exact:true}).fill('Finance');
 await panel.getByRole('button',{name:'+ KPI',exact:true}).click();
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText('10');
 await panel.getByLabel('Tiêu đề widget',{exact:true}).fill('Cost');
 await panel.getByRole('button',{name:'+ KPI',exact:true}).click();
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText(['10','10']);
 await panel.getByLabel('Tiêu đề widget',{exact:true}).fill('Sales');
 await panel.getByLabel('Nguồn widget',{exact:true}).selectOption({label:'sales.xlsx · Data'});
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText(['10','30']);
 await panel.getByLabel('Chiều rộng widget',{exact:true}).selectOption('2');
 await panel.getByRole('button',{name:'Đưa widget Sales lên',exact:true}).click();
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText(['30','10']);
 await panel.getByLabel('Cột lọc Dashboard',{exact:true}).selectOption('Region');
 await panel.getByLabel('Giá trị lọc Dashboard',{exact:true}).fill('N');
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText(['10','3']);
 await panel.getByRole('button',{name:'Lưu Dashboard',exact:true}).click();
 await expect(panel.getByText('Đã lưu Dashboard vào tài khoản.',{exact:true})).toBeVisible();
 expect(accountFixture.settings.dashboards?.[0].widgets.map(w=>w.title)).toEqual(['Sales','Cost']);
 expect(accountFixture.settings.dashboards?.[0].widgets[0].width).toBe(2);
 await page.reload();await expect(page.getByTestId('filtered-count')).toHaveText('180');
 await page.getByRole('button',{name:'Dashboard Designer',exact:true}).click();
 await expect(panel.getByRole('heading',{name:'Finance',exact:true})).toBeVisible();
 const period=panel.getByRole('region',{name:'Dashboard kỳ mới',exact:true});
 await period.getByRole('button',{name:'Chạy kỳ mới Dashboard',exact:true}).click();
 await period.getByLabel('File kỳ mới cho sales.xlsx · Data',{exact:true}).setInputFiles(excel('sales2.xlsx',[['Region','Amount'],['N',40],['S',50]]));
 await period.getByLabel('File kỳ mới cho cost.xlsx · Data',{exact:true}).setInputFiles(excel('cost2.xlsx',[['Region','Amount'],['N',8],['S',9]]));
 await period.getByRole('button',{name:'Chạy Dashboard',exact:true}).click();
 await expect(canvas.getByTestId('dashboard-kpi')).toHaveText(['40','8']);
});
