import {expect,test} from './account-fixture';
import * as XLSX from 'xlsx';
import {readFileSync} from 'node:fs';
test('pivot average distinct and ratio persist, export and replay on next period',async({page,accountFixture},testInfo)=>{
 const file=(name:string,rows:(string|number)[][])=>{const wb=XLSX.utils.book_new();XLSX.utils.book_append_sheet(wb,XLSX.utils.aoa_to_sheet(rows),'Data');return {name,mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})};};
 await page.goto('/');
 await expect(page.getByTestId('filtered-count')).toHaveText('180');
 await page.getByLabel('Chọn dữ liệu Excel',{exact:true}).setInputFiles(file('sales.xlsx',[['Region','Month','Amount','Customer'],['N','Jan',10,'A'],['N','Jan',20,'A'],['S','Feb',90,'B']]));
 await expect(page.getByTestId('metric-total')).toHaveText('120');
 const panel=page.getByRole('region',{name:'Pivot nâng cao',exact:true});
 await panel.getByRole('button',{name:'Mở Pivot',exact:true}).click();
 await panel.getByRole('button',{name:'Thêm cột Pivot',exact:true}).click();
 await panel.getByLabel('Cột Pivot 1',{exact:true}).selectOption('Month');
 await panel.getByLabel('Tên chỉ số 1',{exact:true}).fill('Average');
 await panel.getByLabel('Phép chỉ số 1',{exact:true}).selectOption('avg');
 await panel.getByRole('button',{name:'Thêm chỉ số Pivot',exact:true}).click();
 await panel.getByLabel('Tên chỉ số 2',{exact:true}).fill('Customers');
 await panel.getByLabel('Phép chỉ số 2',{exact:true}).selectOption('distinct');
 await panel.getByLabel('Cột chỉ số 2',{exact:true}).selectOption('Customer');
 await panel.getByRole('button',{name:'Thêm chỉ số Pivot',exact:true}).click();
 await panel.getByLabel('Tên chỉ số 3',{exact:true}).fill('Ratio');
 await panel.getByLabel('Loại chỉ số 3',{exact:true}).selectOption('formula');
 await panel.getByLabel('Vế trái chỉ số 3',{exact:true}).selectOption('m1');
 await panel.getByLabel('Vế phải chỉ số 3',{exact:true}).selectOption('m2');
 await panel.getByRole('button',{name:'Kiểm tra Pivot',exact:true}).click();
 const matrix=panel.getByTestId('pivot-matrix'),alert=panel.getByRole('alert');
 await expect(matrix.or(alert)).toBeVisible({timeout:30000});
 if(await alert.count())throw Error(await alert.innerText());
 const grand=matrix.getByRole('row').filter({has:page.getByRole('rowheader',{name:'Tổng cộng',exact:true})});
 await expect(grand.getByRole('cell').nth(6)).toHaveText('40,00');
 await expect(grand.getByRole('cell').nth(7)).toHaveText('2,00');
 await expect(grand.getByRole('cell').nth(8)).toHaveText('20,00');
 await panel.getByRole('button',{name:'Áp dụng Pivot',exact:true}).click();
 await expect(matrix).toBeVisible();
 await page.getByRole('button',{name:'Lưu workspace',exact:true}).click();
 await expect(page.getByText('Đã lưu workspace vào tài khoản.',{exact:true})).toBeVisible();
 expect(accountFixture.settings.workspace?.slots[0].config.pivot?.measures).toHaveLength(3);
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:'Xuất Excel',exact:true}).click();
 const path=testInfo.outputPath('pivot.xlsx');await (await download).saveAs(path);
 const out=XLSX.read(readFileSync(path),{type:'buffer'});
 const data=XLSX.utils.sheet_to_json(out.Sheets.Pivot,{header:1}) as unknown[][];
 expect(data.find(r=>r[0]==='Tổng cộng')?.slice(-3)).toEqual([40,2,20]);
 await page.reload();await expect(page.getByTestId('filtered-count')).toHaveText('180');
 const runner=page.getByRole('region',{name:'Báo cáo kỳ mới',exact:true});
 await runner.getByRole('button',{name:'Chạy kỳ mới'}).click();
 await runner.getByLabel('File kỳ mới cho sales.xlsx · Data',{exact:true}).setInputFiles(file('next.xlsx',[['Region','Month','Amount','Customer'],['N','Jan',100,'A']]));
 await runner.getByRole('button',{name:'Chạy báo cáo',exact:true}).click();
 await expect(page.getByTestId('metric-total')).toHaveText('100');
 await expect(panel.getByTestId('pivot-matrix')).toBeVisible();
});
