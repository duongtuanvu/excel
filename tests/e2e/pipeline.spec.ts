import {expect,test} from './account-fixture';
import type {Locator} from '@playwright/test';
import * as XLSX from 'xlsx';
function file(name:string,rows:(string|number|null)[][]){
 const wb=XLSX.utils.book_new();XLSX.utils.book_append_sheet(wb,XLSX.utils.aoa_to_sheet(rows),'Sales');
 return {name,mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})};
}
async function preview(panel:Locator,expected:string){
 await panel.getByRole('button',{name:'Kiểm tra pipeline',exact:true}).click();
 const count=panel.getByTestId('pipeline-preview-count'),alert=panel.getByRole('alert');
 await expect(count.or(alert)).toBeVisible({timeout:30000});
 if(await alert.count())throw Error('PIPELINE_PREVIEW_ERROR: '+await alert.innerText());
 await expect(count).toHaveText(expected);
}
