test('strict cast blocks invalid cells, reordered filter makes valid result',async({page})=>{
 await page.goto('/');await expect(page.getByTestId('filtered-count')).toHaveText('180');
 await page.getByLabel('Chọn dữ liệu Excel',{exact:true}).setInputFiles(file('mixed.xlsx',[['Region','Amount'],['A','10'],['B','bad']]));
 await expect(page.getByTestId('filtered-count')).toHaveText('2');
 const panel=page.getByRole('region',{name:'Pipeline biến đổi dữ liệu',exact:true});
 await panel.getByRole('button',{name:'Mở Pipeline',exact:true}).click();
 await panel.getByLabel('Loại bước 1',{exact:true}).selectOption('cast');
 await panel.getByLabel('Cột bước 1',{exact:true}).selectOption('Amount');
 await panel.getByLabel('Kiểu đích bước 1',{exact:true}).selectOption('number');
 await panel.getByRole('button',{name:'Kiểm tra pipeline',exact:true}).click();
 await expect(panel.getByRole('alert')).toContainText('PIPELINE_CONVERSION_FAILED');
 await expect(panel.getByRole('button',{name:'Tạo bảng pipeline',exact:true})).toBeDisabled();
 await expect(page.getByTestId('filtered-count')).toHaveText('2');
 await panel.getByRole('button',{name:'+ Thêm bước',exact:true}).click();
 await panel.getByLabel('Loại bước 2',{exact:true}).selectOption('filter');
 await panel.getByLabel('Cột bước 2',{exact:true}).selectOption('Amount');
 await panel.getByLabel('Điều kiện bước 2',{exact:true}).selectOption('neq');
 await panel.getByLabel('Giá trị bước 2',{exact:true}).fill('bad');
 await panel.getByRole('button',{name:'Đưa bước 2 lên',exact:true}).click();
 await preview(panel,'1 dòng · 2 cột kết quả');
 await panel.getByRole('button',{name:'Tạo bảng pipeline',exact:true}).click();
 await expect(page.getByTestId('metric-total')).toHaveText('10');
 await expect(page.getByTestId('filtered-count')).toHaveText('1');
});
