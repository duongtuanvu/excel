import { expect, test } from './account-fixture';
import * as XLSX from 'xlsx';
function file(name:string,rows:(string|number)[][],sheet='Sales'){
  const wb=XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb,XLSX.utils.aoa_to_sheet(rows),sheet);
  return {name,mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})};
}
test('save account workspace, reload, restore in reverse order and preserve pending slot',async({page,accountFixture})=>{
  await page.goto('/');
  await expect(page.getByTestId('filtered-count')).toHaveText('180');
  const upload=page.getByLabel('Chọn dữ liệu Excel',{exact:true});
  await upload.setInputFiles(file('a.xlsx',[['Region','Amount'],['PRIVATE_RAW_A',10]]));
  await expect(page.getByTestId('metric-total')).toHaveText('10');
  await page.getByLabel('Tên báo cáo').fill('Report A');
  await upload.setInputFiles(file('b.xlsx',[['Region','Amount'],['PRIVATE_RAW_B',99]]));
  await expect(page.getByTestId('metric-total')).toHaveText('99');
  await page.getByLabel('Tên báo cáo').fill('Report B');
  await page.getByRole('button',{name:'Lưu workspace',exact:true}).click();
  await expect(page.getByText('Đã lưu workspace vào tài khoản.',{exact:true})).toBeVisible();
  expect(accountFixture.settings.workspace?.slots.map(s=>s.config.title).sort()).toEqual(['Report A','Report B']);
  expect(JSON.stringify(accountFixture.settings.workspace)).not.toContain('PRIVATE_RAW_');
  await page.reload();
  await expect(page.getByText('0/2 nguồn đã nạp',{exact:true})).toBeVisible();
  await expect(page.getByTestId('filtered-count')).toHaveText('180');
  await page.getByLabel('File cho nguồn b.xlsx · Sales',{exact:true}).setInputFiles(file('bad.xlsx',[['Other'],['bad']]));
  await expect(page.getByRole('alert')).toContainText('SOURCE_SCHEMA_MISMATCH');
  await expect(page.getByText('0/2 nguồn đã nạp',{exact:true})).toBeVisible();
  await page.getByLabel('File cho nguồn b.xlsx · Sales',{exact:true}).setInputFiles(file('feb-b.xlsx',[['Amount','Region'],[199,'South']]));
  await expect(page.getByTestId('metric-total')).toHaveText('199');
  await expect(page.getByLabel('Tên báo cáo')).toHaveValue('Report B');
  await expect(page.getByText('1/2 nguồn đã nạp',{exact:true})).toBeVisible();
  await page.getByLabel('Tên báo cáo').fill('Updated B');
  await page.getByRole('button',{name:'Lưu workspace',exact:true}).click();
  await expect(page.getByText('Đã lưu workspace vào tài khoản.',{exact:true})).toBeVisible();
  expect(accountFixture.settings.workspace?.slots.map(s=>s.config.title).sort()).toEqual(['Report A','Updated B']);
  await page.getByLabel('File cho nguồn a.xlsx · Sales',{exact:true}).setInputFiles(file('feb-a.xlsx',[['Region','Amount'],['North',20]]));
  await expect(page.getByTestId('metric-total')).toHaveText('20');
  await expect(page.getByLabel('Tên báo cáo')).toHaveValue('Report A');
  await expect(page.getByText('2/2 nguồn đã nạp',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Mở nguồn b.xlsx · Sales',exact:true}).click();
  await expect(page.getByTestId('metric-total')).toHaveText('199');
  await expect(page.getByLabel('Tên báo cáo')).toHaveValue('Updated B');
  await page.getByRole('button',{name:'Mở không gian cá nhân'}).click();
  await page.getByLabel('Tên hiển thị').fill('Finance');
  await page.getByRole('button',{name:'Lưu hồ sơ'}).click();
  await expect(page.getByText('Đã cập nhật hồ sơ.')).toBeVisible();
  expect(accountFixture.settings.workspace?.slots).toHaveLength(2);
});
test('forget an unloaded saved slot only after confirmation',async({page,accountFixture})=>{
  accountFixture.settings.workspace={version:1,slots:[{id:crypto.randomUUID(),alias:'Pending',sheet:'Sales',columns:[{name:'Amount',kind:'number'}],config:{title:'Saved report',groups:[],metric:'Amount',aggregate:'sum',filters:[],chart:'bar',sort:'desc'}}]};
  await page.goto('/');
  await expect(page.getByText('0/1 nguồn đã nạp',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Bỏ cấu hình',exact:true}).click();
  await page.getByRole('button',{name:'Hủy',exact:true}).click();
  expect(accountFixture.settings.workspace?.slots).toHaveLength(1);
  await page.getByRole('button',{name:'Bỏ cấu hình',exact:true}).click();
  await page.getByRole('button',{name:'Xác nhận bỏ',exact:true}).click();
  await expect(page.getByText('Chưa lưu workspace',{exact:true})).toBeVisible();
  expect(accountFixture.settings.workspace).toBeNull();
});
