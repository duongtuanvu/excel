import type { Config, Report } from './model';
import type { Workspace } from './source-model';
import type { SavedSource, SavedWorkspace } from './workspace-model';
import type { PeriodFile, PeriodResult } from './period-model';
import type { SourceProfile, Distribution } from './profile-model';
import type { SchemaRule, SchemaPreview } from './schema-model';
import type { ImportLayout, LayoutPreview, ColumnMapping, ReplacementPreview, MappedPreview } from './import-model';
import type { BatchFile, BatchPreview } from './batch-model';
import type { ModelInput,ModelPreview } from './data-model';
import type { PipelineInput,PipelinePreview } from './pipeline-model';
import type {PivotResult} from './pivot-config';
type SourceVersion={sourceId:string;revision:number};
export type Requests={
  demo:{input:null;output:Workspace};
  import:{input:{name:string;bytes:ArrayBuffer};output:Workspace};
  sheet:{input:{sheet:string};output:Workspace};
  activateSource:{input:{sourceId:string};output:Workspace};
  renameSource:{input:{sourceId:string;alias:string};output:Workspace};
  removeSource:{input:{sourceId:string};output:Workspace};
  replaceSource:{input:SourceVersion&{name:string;bytes:ArrayBuffer};output:Workspace};
  restoreSource:{input:{slot:SavedSource;name:string;bytes:ArrayBuffer};output:Workspace};
  runPeriod:{input:{saved:SavedWorkspace;outputId:string;files:PeriodFile[];confirmed:string[]};output:PeriodResult};
  previewPipeline:{input:PipelineInput;output:PipelinePreview};
  createPipeline:{input:PipelineInput;output:Workspace};
  previewModel:{input:ModelInput;output:ModelPreview};
  createModel:{input:ModelInput&{confirmExpansion:boolean};output:Workspace};
  previewBatch:{input:{files:BatchFile[]};output:BatchPreview};
  applyBatch:{input:{files:BatchFile[]};output:Workspace};
  previewLayout:{input:SourceVersion&{layout:ImportLayout|null;config:Config};output:LayoutPreview};
  applyLayout:{input:SourceVersion&{layout:ImportLayout|null;config:Config;resetReport:boolean};output:{workspace:Workspace;config:Config}};
  inspectReplacement:{input:SourceVersion&{name:string;bytes:ArrayBuffer};output:ReplacementPreview};
  previewMapped:{input:SourceVersion&{name:string;bytes:ArrayBuffer;mapping:ColumnMapping[]};output:MappedPreview};
  applyMapped:{input:SourceVersion&{name:string;bytes:ArrayBuffer;mapping:ColumnMapping[]};output:Workspace};
  previewSchema:{input:SourceVersion&{rules:SchemaRule[];config:Config};output:SchemaPreview};
  applySchema:{input:SourceVersion&{rules:SchemaRule[];config:Config};output:{workspace:Workspace;config:Config}};
  profile:{input:SourceVersion;output:SourceProfile};
  distribution:{input:SourceVersion&{columnId:string};output:Distribution};
  previewPivot:{input:SourceVersion&{config:Config};output:PivotResult};
  report:{input:SourceVersion&{config:Config;page:number};output:Report};
  export:{input:SourceVersion&{config:Config;format:'xlsx'|'csv'};output:{bytes:ArrayBuffer;name:string;mime:string}};
};
export type Request={ [K in keyof Requests]:{id:number;type:K;input:Requests[K]['input']} }[keyof Requests];
export type Response={id:number;ok:true;data:unknown}|{id:number;ok:false;error:string};
