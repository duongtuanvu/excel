export function applicableDefinitions(form: FormId, jointStock: boolean): Definition[] {
  if (form === 'B01') {
    if (jointStock) return FORM_DEFINITIONS.B01.map(item => item.code === '411' ? { ...item, terms: ['411a', '411b'] } : item);
    return FORM_DEFINITIONS.B01.filter(item => item.code !== '411a' && item.code !== '411b');
  }
  if (form === 'B02' && !jointStock) return FORM_DEFINITIONS.B02.filter(item => item.code !== '70' && item.code !== '71');
  return FORM_DEFINITIONS[form];
}
